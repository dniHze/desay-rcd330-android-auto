#!/usr/bin/env python3
"""The media player's functions our library hooks for the USB cover, as C++ for one base: addresses,
sizes and an FNV-1a hash of each function's code bytes.

    python3 -I i18n/gen_media.py <stock bin/mediaplayer> <out .inc>

i18n/lib/media.cpp hooks a running media player only when every function below is at its address
with exactly these bytes (the app is ET_EXEC, text from file offset 0 at 0x8000). Another build
keeps its music note. Generated at build time from the firmware; never committed.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fw  # noqa: E402
import gen_settings  # noqa: E402

FUNCS = [
    # (C++ name in the table, mangled symbol)
    ("set_id3", "_ZN14SVPPlayerState6SetID3ERKNS_3ID3E"),  # hooked: a track's tags, with its cover
    ("usb_id3", "_ZN21SVPMusicPlayerMainDlg9UpdateID3Ev"),  # hooked: the USB screen shows the tags
]


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    e = fw.Elf(sys.argv[1])
    if e.type != 2 or e.off(0x8000) != 0:
        sys.exit("mediaplayer: not ET_EXEC with its text at 0x8000")
    syms = gen_settings.symbols(e)
    with open(sys.argv[2], "w") as f:
        f.write("// Generated by i18n/gen_media.py. Not committed.\n")
        f.write("static const MediaFunc kMediaFuncs[] = {\n")
        for key, sym in FUNCS:
            if sym not in syms:
                sys.exit("mediaplayer: %s not found" % sym)
            va, size = syms[sym]
            code = e.data[e.off(va):e.off(va) + size]
            f.write("    {\"%s\", 0x%x, 0x%x, 0x%08xu},\n" % (key, va, size, gen_settings.fnv(code)))
        f.write("};\n")
    print("%s: %d functions" % (sys.argv[2], len(FUNCS)))


if __name__ == "__main__":
    main()
