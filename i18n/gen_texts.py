#!/usr/bin/env python3
"""Our library's own texts (the sheet's "lit:aa:<key>" rows: Settings > Appearance), as C++: each
key, its entry in aa_lang.bin's own texts (literals.entries), its English and its Chinese.

    python3 -I i18n/gen_texts.py <out .inc>

The other languages' texts are in aa_lang.bin, which build_table.py writes from the same rows;
English and Chinese have no table there, so they are compiled in. Never committed.
"""
import csv
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import extract  # noqa: E402
import literals  # noqa: E402


def c(s):
    return '"%s"' % s.replace("\\", "\\\\").replace('"', '\\"').replace("\\\\n", "\\n")


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    with open(extract.SHEET, encoding="utf-8-sig", newline="") as f:
        lits = [r for r in csv.DictReader(f) if r["id"].startswith("lit:")]
    ents = literals.entries(lits)
    rows = [r for r in lits if r["id"].startswith("lit:aa:")]
    with open(sys.argv[1], "w") as f:
        f.write("// Generated by i18n/gen_texts.py from i18n/strings.csv. Not committed.\n")
        f.write("static const OwnText kOwnTexts[] = {\n")
        for r in rows:
            k = next(i for i, (rid, j, _) in enumerate(ents) if rid == r["id"] and j < 0)
            f.write("    {%s, %d, %s, %s},\n" % (c(r["id"][len("lit:aa:"):]), k, c(r["en"]), c(r["zh"])))
        f.write("};\n")
    print("%s: %d texts" % (sys.argv[1], len(rows)))


if __name__ == "__main__":
    main()
