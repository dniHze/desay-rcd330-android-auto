#!/usr/bin/env python3
"""The phrase book of a stock (or rebranded) libUIPublic.so as C++ for our library.

    python3 -I i18n/gen_table.py <libUIPublic.so> <plain libUIPublic.so> <out .inc>

Writes AA_N, the Chinese and English texts byte for byte as the given library has them
(aa_stock_rows), the initial s_Items pointing at them, and AA_EN_MD5: the md5 of the plain
(not rebranded) library's English texts, each followed by a NUL. strings.bin carries the same
md5, so a data file built for another phrase book is refused. Generated at build time from the
firmware; never committed.
"""
import hashlib
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fw  # noqa: E402


def literal(b):
    """A C string literal of the bytes: printable ASCII as is, the rest as 3-digit octal."""
    out = []
    for c in b:
        ch = chr(c)
        if ch in '"\\':
            out.append("\\" + ch)
        elif 32 <= c < 127 and ch != "?":
            out.append(ch)
        else:
            out.append("\\%03o" % c)
    return '"' + "".join(out) + '"'


def en_md5(rows):
    return hashlib.md5(b"".join(en + b"\0" for _, _, en in rows)).hexdigest()


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    rows = fw.phrasebook(sys.argv[1])
    plain = fw.phrasebook(sys.argv[2])
    if len(rows) != len(plain):
        sys.exit("the two libraries have different phrase counts")
    n = len(rows)
    with open(sys.argv[3], "w") as f:
        f.write("// Generated by i18n/gen_table.py from %s (md5 %s). Not committed.\n"
                % (os.path.basename(sys.argv[1]), hashlib.md5(open(sys.argv[1], "rb").read()).hexdigest()))
        f.write("#define AA_N %d\n" % n)
        f.write('#define AA_EN_MD5 "%s"\n' % en_md5(plain))
        f.write("static const char* const aa_stock_rows[AA_N][2] = {\n")
        for _, zh, en in rows:
            f.write("    {%s, %s},\n" % (literal(zh), literal(en)))
        f.write("};\n")
        f.write("StringItem s_Items[AA_N] = {\n")
        for i in range(n):
            f.write("    {%d, const_cast<const char**>(aa_stock_rows[%d])},\n" % (i, i))
        f.write("};\n")
    print("%s: %d phrases, EN md5 %s" % (sys.argv[3], n, en_md5(plain)))


if __name__ == "__main__":
    main()
