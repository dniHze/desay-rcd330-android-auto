#!/usr/bin/env python3
"""The radio app's functions and data our library uses for station names on the FM presets, as C++
for one base: addresses, sizes and an FNV-1a hash of each function's code bytes.

    python3 -I i18n/gen_radio.py <stock bin/radio> <out .inc>

i18n/lib/radio.cpp hooks a running radio app only when every function below is at its address
with exactly these bytes (the app is ET_EXEC, text from file offset 0 at 0x8000, like the Settings
app). Another build leaves the presets as they are. Generated at build time from the firmware;
never committed.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fw  # noqa: E402
import gen_settings  # noqa: E402

FUNCS = [
    # (C++ name in the table, mangled symbol)
    ("update_fm", "_ZN13CRadioMainDlg14UpdateFMPresetEv"),  # hooked: the main screen's FM preset tiles
    ("get_ps", "_ZN13CRadioDataMgr9GetPsNameEPc"),  # hooked: the station name RDS gives now (8 bytes)
    ("preset_freq", "_ZN13CRadioDataMgr23GetCurrentPresetByIndexEt"),  # called: preset i's frequency
    ("set_freq", "_ZN23PresetListDataExchanger11SetTextFreqEPKc"),  # called: a tile's frequency text
    ("set_unit", "_ZN23PresetListDataExchanger11SetTextUnitEPKc"),  # called: a tile's unit text (MHz)
    ("item_ctrl", "_ZN23PresetListDataExchanger16OnUpdateItemCtrlEiP11ISkCtrlBase"),  # hooked: a tile's nodes
]
DATA = [
    ("AA_RADIO_FM_FREQ", "_ZN13CRadioDataMgr8m_FMFreqE"),  # u16, 10 kHz units (8830: 88.3 MHz)
    ("AA_RADIO_CUR_BAND", "_ZN13CRadioDataMgr9m_CurBandE"),  # int, 1: FM
    ("AA_RADIO_ITEM_TI", "_ZTI23PresetListDataExchanger"),  # the tiles' type, for the cast
]


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    e = fw.Elf(sys.argv[1])
    if e.type != 2 or e.off(0x8000) != 0:
        sys.exit("radio: not ET_EXEC with its text at 0x8000")
    syms = gen_settings.symbols(e)
    with open(sys.argv[2], "w") as f:
        f.write("// Generated by i18n/gen_radio.py. Not committed.\n")
        for name, sym in DATA:
            addr = gen_settings.data_symbol(e, sym)
            if not addr:
                sys.exit("radio: %s not found" % sym)
            f.write("#define %s 0x%x\n" % (name, addr))
        f.write("static const RadioFunc kRadioFuncs[] = {\n")
        for key, sym in FUNCS:
            if sym not in syms:
                sys.exit("radio: %s not found" % sym)
            va, size = syms[sym]
            code = e.data[e.off(va):e.off(va) + size]
            f.write("    {\"%s\", 0x%x, 0x%x, 0x%08xu},\n" % (key, va, size, gen_settings.fnv(code)))
        f.write("};\n")
    print("%s: %d functions, %d data" % (sys.argv[2], len(FUNCS), len(DATA)))


if __name__ == "__main__":
    main()
