#!/usr/bin/env python3
"""The launcher's functions our library hooks for Settings > Appearance, as C++ for one base: their
addresses, sizes and an FNV-1a hash of their code bytes.

    python3 -I i18n/gen_launcher.py <stock bin/launcher> <out .inc>

i18n/lib/appearance.cpp hooks a running launcher only when every function below is at its address
with exactly these bytes (the launcher is ET_EXEC, text from file offset 0 at 0x8000, like the
Settings app). Another build leaves the colour and the logo to the coding. Generated at build time
from the firmware; never committed.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fw  # noqa: E402
import gen_settings  # noqa: E402

FUNCS = [
    # (C++ name in the table, mangled symbol)
    ("init_skin", "_ZN9SVPRmtCan12InitSkinTypeEv"),
    ("desc_skin", "_ZN9SVPRmtCan15SetDescSkinTypeEv"),
    ("bap_view_data", "_ZN9SVPRmtCan24OnBapScreenViewDataEventEN10SVPCanType22SVPBapScreenViewIdTypeERSt6vectorIhSaIhEE"),
]


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    e = fw.Elf(sys.argv[1])
    if e.type != 2 or e.off(0x8000) != 0:
        sys.exit("launcher: not ET_EXEC with its text at 0x8000")
    syms = gen_settings.symbols(e)
    with open(sys.argv[2], "w") as f:
        f.write("// Generated by i18n/gen_launcher.py. Not committed.\n")
        f.write("static const LauncherFunc kLauncherFuncs[] = {\n")
        for key, sym in FUNCS:
            if sym not in syms:
                sys.exit("launcher: %s not found" % sym)
            va, size = syms[sym]
            code = e.data[e.off(va):e.off(va) + size]
            f.write("    {\"%s\", 0x%x, 0x%x, 0x%08xu},\n" % (key, va, size, gen_settings.fnv(code)))
        f.write("};\n")
    print("%s: %d functions" % (sys.argv[2], len(FUNCS)))


if __name__ == "__main__":
    main()
